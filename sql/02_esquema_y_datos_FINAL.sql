CREATE TABLE clientes (
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador VARCHAR2(30) NOT NULL UNIQUE,
    nombre VARCHAR2(120) NOT NULL,
    telefono VARCHAR2(30),
    correo VARCHAR2(120),
    saldo_puntos NUMBER DEFAULT 0 NOT NULL CHECK (saldo_puntos >= 0),
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1)),
    fecha_registro TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE productos (
    codigo VARCHAR2(20) PRIMARY KEY,
    categoria VARCHAR2(30) NOT NULL CHECK (categoria IN ('SANDWICH','BEBIDA','ACOMPANAMIENTO')),
    nombre VARCHAR2(120) NOT NULL,
    precio NUMBER(10,2) NOT NULL CHECK (precio >= 0),
    existencia NUMBER DEFAULT 0 NOT NULL CHECK (existencia >= 0),
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1))
);

CREATE TABLE menus (
    id_menu NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(20) NOT NULL UNIQUE,
    nombre VARCHAR2(120) NOT NULL,
    precio NUMBER(10,2) NOT NULL CHECK (precio >= 0),
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1))
);

CREATE TABLE menu_componentes (
    id_menu NUMBER NOT NULL,
    producto_codigo VARCHAR2(20) NOT NULL,
    cantidad NUMBER DEFAULT 1 NOT NULL CHECK (cantidad > 0),
    CONSTRAINT pk_menu_componentes PRIMARY KEY (id_menu, producto_codigo),
    CONSTRAINT fk_mc_menu FOREIGN KEY (id_menu) REFERENCES menus(id_menu),
    CONSTRAINT fk_mc_producto FOREIGN KEY (producto_codigo) REFERENCES productos(codigo)
);

CREATE TABLE pedidos (
    id_pedido NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente NUMBER NOT NULL,
    fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    estado VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL CHECK (estado IN ('PENDIENTE','PAGADO','ENTREGADO','ANULADO')),
    total NUMBER(10,2) NOT NULL CHECK (total >= 0),
    puntos_generados NUMBER DEFAULT 0 NOT NULL CHECK (puntos_generados >= 0),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente)
);

CREATE TABLE detalle_pedido (
    id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido NUMBER NOT NULL,
    tipo_item VARCHAR2(15) NOT NULL CHECK (tipo_item IN ('PRODUCTO','MENU')),
    producto_codigo VARCHAR2(20),
    id_menu NUMBER,
    descripcion VARCHAR2(160) NOT NULL,
    cantidad NUMBER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMBER(10,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMBER(10,2) NOT NULL CHECK (subtotal >= 0),
    puntos NUMBER DEFAULT 0 NOT NULL CHECK (puntos >= 0),
    CONSTRAINT fk_det_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
    CONSTRAINT fk_det_producto FOREIGN KEY (producto_codigo) REFERENCES productos(codigo),
    CONSTRAINT fk_det_menu FOREIGN KEY (id_menu) REFERENCES menus(id_menu),
    CONSTRAINT ck_det_objetivo CHECK (
        (tipo_item='PRODUCTO' AND producto_codigo IS NOT NULL AND id_menu IS NULL) OR
        (tipo_item='MENU' AND producto_codigo IS NULL AND id_menu IS NOT NULL)
    )
);

CREATE TABLE pagos (
    id_pago NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido NUMBER NOT NULL UNIQUE,
    fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    metodo VARCHAR2(10) NOT NULL CHECK (metodo IN ('EFECTIVO','TARJETA')),
    monto NUMBER(10,2) NOT NULL CHECK (monto >= 0),
    dinero_recibido NUMBER(10,2),
    cambio NUMBER(10,2),
    referencia VARCHAR2(80),
    aprobado NUMBER(1) DEFAULT 1 NOT NULL CHECK (aprobado IN (0,1)),
    CONSTRAINT fk_pago_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido)
);

CREATE TABLE movimientos_inventario (
    id_movimiento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_codigo VARCHAR2(20) NOT NULL,
    fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    cantidad NUMBER NOT NULL,
    tipo VARCHAR2(20) NOT NULL CHECK (tipo IN ('ABASTECIMIENTO','VENTA','CANJE')),
    referencia VARCHAR2(80),
    CONSTRAINT fk_movinv_producto FOREIGN KEY (producto_codigo) REFERENCES productos(codigo)
);

CREATE TABLE recompensas (
    id_recompensa NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    puntos_necesarios NUMBER NOT NULL CHECK (puntos_necesarios > 0),
    tipo_objetivo VARCHAR2(10) NOT NULL CHECK (tipo_objetivo IN ('PRODUCTO','MENU')),
    producto_codigo VARCHAR2(20),
    id_menu NUMBER,
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1)),
    CONSTRAINT fk_rec_producto FOREIGN KEY (producto_codigo) REFERENCES productos(codigo),
    CONSTRAINT fk_rec_menu FOREIGN KEY (id_menu) REFERENCES menus(id_menu),
    CONSTRAINT ck_rec_objetivo CHECK (
        (tipo_objetivo='PRODUCTO' AND producto_codigo IS NOT NULL AND id_menu IS NULL) OR
        (tipo_objetivo='MENU' AND producto_codigo IS NULL AND id_menu IS NOT NULL)
    )
);

CREATE TABLE movimientos_puntos (
    id_movimiento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente NUMBER NOT NULL,
    fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    tipo VARCHAR2(15) NOT NULL CHECK (tipo IN ('ACUMULACION','CANJE')),
    referencia VARCHAR2(80),
    puntos NUMBER NOT NULL,
    CONSTRAINT fk_movpts_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente)
);

CREATE TABLE canjes (
    id_canje NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente NUMBER NOT NULL,
    id_recompensa NUMBER NOT NULL,
    fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    puntos_utilizados NUMBER NOT NULL CHECK (puntos_utilizados > 0),
    CONSTRAINT fk_canje_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
    CONSTRAINT fk_canje_recompensa FOREIGN KEY (id_recompensa) REFERENCES recompensas(id_recompensa)
);

