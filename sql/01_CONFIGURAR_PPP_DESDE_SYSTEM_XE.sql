ALTER SESSION SET CONTAINER = XEPDB1;

SELECT USER AS USUARIO,
       SYS_CONTEXT('USERENV','CON_NAME') AS CONTENEDOR
FROM DUAL;

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_existe
    FROM DBA_USERS
    WHERE USERNAME = 'PPP';

    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER PPP IDENTIFIED BY PPP123';
    ELSE
        EXECUTE IMMEDIATE 'ALTER USER PPP IDENTIFIED BY PPP123 ACCOUNT UNLOCK';
    END IF;
END;
/

GRANT CREATE SESSION TO PPP;
GRANT CREATE TABLE TO PPP;
GRANT CREATE SEQUENCE TO PPP;
GRANT CREATE VIEW TO PPP;
GRANT CREATE PROCEDURE TO PPP;
GRANT CREATE TRIGGER TO PPP;

ALTER USER PPP QUOTA UNLIMITED ON USERS;
